"""scripts/rules_md.py
-------------------
Generate `docs/rules.md` and the skill's `references/mechanisms.md` from the rule registry
and the policy.

The policy (`src/aisafe/policy/mechanisms.yaml`) says what each mechanism is and what it is
distinct from; the rule classes (`aisafe.rules.ALL_RULES`) say what is detected, at which
default severity, evidence status and decision, which sub-findings exist (a `SUBS` class
attribute, when the rule defines one: a tuple of `(sub or None, severity, evidence_status,
decision, one-line meaning)`), what the remediation removes, which laws and standards are
pointed at, and what is known to go wrong. Both documents are rendered whole from those two
sources, so nothing in them can drift from the code.

    python scripts/rules_md.py            # rewrite both documents
    python scripts/rules_md.py --check    # exit 1 when either differs, write nothing
    python scripts/rules_md.py --skill    # only the skill's references/mechanisms.md
    python scripts/rules_md.py --docs     # only docs/rules.md

Run from the repo root (the script puts `src/` on sys.path itself), then
`python scripts/sync_skill.py` so the plugin mirror follows. Not shipped.
"""

from __future__ import annotations

import argparse
import sys
import textwrap
from pathlib import Path
from typing import Any, Sequence

REPO = Path(__file__).resolve().parents[1]
SRC = REPO / "src"
DOCS_MD = REPO / "docs" / "rules.md"
SKILL_MD = REPO / "src" / "aisafe" / "skills" / "ai-safety-audit" / "references" / "mechanisms.md"

# The documents' own wrap width; longer lines are only tables and headings.
WIDTH = 92
UNMEASURED = "UNMEASURED"

_DOCS_HEAD = """# Rules

Generated by `scripts/rules_md.py` from the rule registry (`aisafe.rules`) and the policy
(`policy/mechanisms.yaml`, version {version}); do not edit by hand
(`python scripts/rules_md.py --check` fails on drift).

Each mechanism below is a practice the charter prohibits. A rule serves one mechanism and
reports what it found as a finding with three separate parts: an evidence status (what was
established), a policy decision (what the policy says about it) and a remediation (what to
remove from the chain). The number inside a rule id is a label; the order of the sections is
the policy's. Every rule is {unmeasured}: no precision figure exists for it yet, and an
unmeasured rule still runs. A finding is never a verdict on the product, and absence of a
finding is not evidence of safety.

Severity is about what the mechanism does to the person, never about which rule found it.
The policy's criteria, highest first:
"""

_SKILL_HEAD = """# Mechanisms and rules

Generated by `scripts/rules_md.py` from the policy (version {version}) and the rule
registry; do not edit by hand. Read this when a finding's mechanism, decision or sub-finding
needs explaining to the person you work with: the text below is what the policy and the rule
class say, not a paraphrase. Every rule is {unmeasured}; a finding is evidence plus the
policy's decision, never a verdict, and absence of a finding is not evidence of safety.
"""

_VOCABULARY_HEAD = "## Vocabulary"
_EVIDENCE_HEAD = "Evidence statuses, weakest to strongest (`unknown` stands apart):"
_DECISIONS_HEAD = "Decisions:"
_CONTROLS_HEAD = "Control statuses, each stronger than the one before:"
_EXEMPTIONS_HEAD = (
    "Weighed in a contextual review and never closing a finding on their own "
    "(`not_automatic_exemptions`):"
)


def _value(obj: Any) -> str:
    """An enum's value, else the object as text."""
    return str(getattr(obj, "value", obj))


def _wrap(text: str, indent: str = "", first: str | None = None) -> list[str]:
    """Wrap `text` at the document width; `first` is the first line's own indent."""
    return textwrap.wrap(
        " ".join(str(text).split()),
        width=WIDTH,
        initial_indent=first if first is not None else indent,
        subsequent_indent=indent,
        break_long_words=False,
        break_on_hyphens=False,
    )


def _bullets(items: Sequence[Any]) -> list[str]:
    out: list[str] = []
    for item in items:
        out.extend(_wrap(str(item), indent="  ", first="- "))
    return out


def _cell(text: Any) -> str:
    return " ".join(str(text).split()).replace("|", "/")


def _subs_of(rule: Any) -> list[tuple[str, str, str, str, str]]:
    """The `SUBS` rows of a rule as text cells; a short or odd row is reported, not hidden."""
    rows: list[tuple[str, str, str, str, str]] = []
    for entry in getattr(rule, "SUBS", None) or ():
        parts = list(entry) + [""] * (5 - len(entry))
        sub, severity, status, decision, meaning = parts[:5]
        rows.append(
            (
                "(none)" if sub in (None, "") else f"/{sub}",
                _value(severity),
                _value(status),
                _value(decision),
                _cell(meaning),
            )
        )
    return rows


def render_rule(rule: Any) -> list[str]:
    """One `###` section per rule: defaults, sub-findings, references, remediation,
    alternatives, known failure modes and the change log."""
    version = int(getattr(rule, "version", 1))
    lines = [f"### {rule.id} v{version}: {rule.title}", ""]
    recommendation = rule.recommendation
    lines += _wrap(
        f"Default: severity {_value(rule.severity)}; evidence {_value(rule.default_evidence_status)}; "
        f"decision {_value(rule.default_decision)}; basis {_value(rule.basis)}; "
        f"evidence kind {_value(rule.evidence_kind)}; match {_value(rule.match_kind)}; "
        f"tier {_value(recommendation.tier)}; precision "
        + (UNMEASURED if rule.measured_precision is None else f"{rule.measured_precision:.2f}")
        + "."
    )
    if getattr(rule, "requires_ai_surface", False):
        lines += _wrap("Runs only when a unit in the inventory has an AI surface.")
    lines.append("")
    subs = _subs_of(rule)
    if subs:
        lines += [
            "Sub-findings:",
            "",
            "| sub | severity | evidence | decision | meaning |",
            "|---|---|---|---|---|",
        ]
        for sub, severity, status, decision, meaning in subs:
            lines.append(f"| {sub} | {severity} | {status} | {decision} | {meaning} |")
    else:
        lines.append("Sub-findings: none.")
    lines.append("")
    references = list(getattr(rule, "references", ()) or ())
    lines += _wrap("References: " + (", ".join(references) if references else "none") + ".")
    removes = list(getattr(recommendation, "removes", ()) or ())
    removes_text = ", ".join(removes) if removes else "nothing named"
    lines += _wrap(
        f"Remediation ({_value(recommendation.tier)}, removes {removes_text}): "
        f"{recommendation.summary}"
    )
    alternatives = list(getattr(recommendation, "alternatives", ()) or ())
    if alternatives:
        lines += ["", "Alternatives:", ""]
        lines += _bullets(alternatives)
    failure_modes = list(getattr(rule, "known_failure_modes", ()) or ())
    lines += ["", "Known failure modes:", ""]
    lines += _bullets(failure_modes) if failure_modes else ["- none recorded"]
    changed = list(getattr(rule, "changed", ()) or ())
    lines += ["", f"Changes since version 1 (now v{version}):", ""]
    lines += _bullets(changed) if changed else ["- none recorded"]
    lines.append("")
    return lines


def _vocabulary(policy: Any) -> list[str]:
    lines = [_VOCABULARY_HEAD, "", _EVIDENCE_HEAD, ""]
    lines += _bullets([f"`{key}`: {text}" for key, text in policy.evidence_statuses.items()])
    lines += ["", _DECISIONS_HEAD, ""]
    lines += _bullets([f"`{key}`: {text}" for key, text in policy.decisions.items()])
    lines += ["", _CONTROLS_HEAD, ""]
    lines += _bullets([f"`{key}`: {text}" for key, text in policy.control_statuses.items()])
    lines += ["", _EXEMPTIONS_HEAD, ""]
    lines += _bullets(list(policy.not_automatic_exemptions))
    lines.append("")
    return lines


def render(policy: Any, rules: Sequence[Any], *, skill: bool, missing: Sequence[str]) -> str:
    """The whole document, LF-terminated, ASCII."""
    head = _SKILL_HEAD if skill else _DOCS_HEAD
    lines = head.format(version=policy.version, unmeasured=UNMEASURED).rstrip("\n").split("\n")
    lines.append("")
    if not skill:
        lines += _bullets([f"`{key}`: {text}" for key, text in policy.severity_criteria.items()])
        lines.append("")
    lines += _vocabulary(policy)
    by_id = {rule.id: rule for rule in rules}
    placed: set[str] = set()
    for mechanism in policy.mechanisms:
        lines += [f"## {mechanism.id} {mechanism.name}", ""]
        lines += _wrap(f"Prohibited: {mechanism.prohibited}")
        lines.append("")
        lines += _wrap(f"Distinct from: {mechanism.distinct_from}")
        lines.append("")
        lines += _wrap("Rules: " + ", ".join(mechanism.rules) + ".")
        lines.append("")
        for rule_id in mechanism.rules:
            rule = by_id.get(rule_id)
            if rule is None:
                lines += [
                    f"### {rule_id}: not in this installation's rule registry",
                    "",
                    "The policy lists this rule; the registry does not carry it, so it did not "
                    "run and nothing below describes it.",
                    "",
                ]
                continue
            placed.add(rule_id)
            lines += render_rule(rule)
    unplaced = [rule for rule in rules if rule.id not in placed]
    if unplaced:
        lines += ["## Not placed by the policy", ""]
        lines += _wrap(
            "These registered rules serve no mechanism the policy lists; their findings "
            "carry priority 99 and are grouped last."
        )
        lines.append("")
        for rule in unplaced:
            lines += render_rule(rule)
    tail = f"Generated from policy {policy.version} and {len(rules)} registered rules"
    if missing:
        tail += f"; rule modules missing from this installation: {', '.join(sorted(missing))}"
    lines += _wrap(tail + ".")
    return "\n".join(lines).rstrip("\n") + "\n"


def _load() -> tuple[Any, list[Any], list[str]]:
    sys.path.insert(0, str(SRC))
    from aisafe.policy import load_policy
    from aisafe.rules import ALL_RULES, MISSING_RULE_MODULES

    return load_policy(), list(ALL_RULES), list(MISSING_RULE_MODULES)


def _ascii_bytes(text: str, label: str) -> bytes:
    try:
        return text.encode("ascii")
    except UnicodeEncodeError as exc:
        raise SystemExit(
            f"{label}: a rule or the policy carries a non-ASCII character "
            f"(offset {exc.start}); every string a renderer emits is ASCII"
        ) from exc


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="rules_md.py",
        description=(
            "Render docs/rules.md and the skill's references/mechanisms.md from the rule "
            "registry and the policy."
        ),
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="Compare and exit 1 when either document differs; write nothing.",
    )
    which = parser.add_mutually_exclusive_group()
    which.add_argument("--skill", action="store_true", help="Only the skill's mechanisms.md.")
    which.add_argument("--docs", action="store_true", help="Only docs/rules.md.")
    args = parser.parse_args(argv)

    policy, rules, missing = _load()
    targets: list[tuple[Path, bool]] = []
    if not args.skill:
        targets.append((DOCS_MD, False))
    if not args.docs:
        targets.append((SKILL_MD, True))

    drift: list[str] = []
    for path, skill in targets:
        label = path.relative_to(REPO).as_posix()
        rendered = _ascii_bytes(render(policy, rules, skill=skill, missing=missing), label)
        current = path.read_bytes() if path.is_file() else None
        if current == rendered:
            continue
        drift.append(f"{label}: " + ("missing" if current is None else "differs"))
        if not args.check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(rendered)  # bytes: keep LF on Windows

    for line in drift:
        print(("differs: " if args.check else "rewrote: ") + line)
    if missing:
        print(
            "note: rule modules missing from this installation: "
            + ", ".join(sorted(missing))
            + "; the documents say so",
            file=sys.stderr,
        )
    if args.check:
        if drift:
            print(f"{len(drift)} difference(s); run without --check to fix", file=sys.stderr)
            return 1
        print(f"in sync: {len(rules)} rules, policy {policy.version}, {len(targets)} document(s)")
        return 0
    print(
        f"rendered {len(targets)} document(s) from {len(rules)} rules under policy "
        f"{policy.version}; {len(drift)} rewritten"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
