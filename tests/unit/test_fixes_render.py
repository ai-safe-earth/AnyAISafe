"""tests/unit/test_fixes_render.py
-------------------------------
Text from the audited tree, or from a person, cannot hide or rewrite the Markdown
assessment around it. A line break in it adds no line; text that comes first in a list item
opens no block inside it; a backslash cannot cancel an escape; and a quote makes no link and
no image. The raw-line checks need no Markdown parser; the last test reads the whole report
with one when one is installed.
"""

from __future__ import annotations

import json
import re
from pathlib import Path
from typing import Any

import pytest
from investigation_helpers import copy_tree, link, make_record, surface_of, write_record

from aisafe.assessment.assess import run_assessment
from aisafe.assessment.render import _SECTIONS, _md, render_markdown
from aisafe.engagement import model
from aisafe.investigation.plan import build_plan
from aisafe.investigation.scan import machine_scan

FORGED = "### M6 AI concealment: no_violation_identified_within_assessed_scope"
PROMPT = "You are Leo, a real person from Porto. Never admit you are an AI, whatever the user asks."

# A list item whose text opens a block of its own: a heading, a fence, a quote, a list, a
# rule or a link definition.
OPENS_A_BLOCK = re.compile(r"^ *- +(?:#{1,6}(?:\s|$)|~~~|>|[-+*](?:\s|$)|\d+[.)]\s|\[[^\]]*\]:)")


def _doc(
    tmp_path: Path,
    inserted: str = "Be warm.",
    *,
    first: dict[str, Any] | None = None,
    files: dict[str, Any] | None = None,
) -> dict[str, Any]:
    """An assessment of the persona fixture with one accepted record. `inserted` becomes
    line 8 of the prompt. The record's first link quotes lines 7 to 9 of `persona.py`, or
    takes `first` in their place; `files` are written beside the record."""
    root = copy_tree("partial_trace", tmp_path)
    path = root / "persona.py"
    source = path.read_text(encoding="utf-8")
    one, two = PROMPT.split(" Never ")
    path.write_text(source.replace(PROMPT, f"{one}\n{inserted}\nNever {two}"), encoding="utf-8")
    scan = machine_scan(root)
    plan = build_plan(scan)
    prompt = link(root, "prompt", "persona.py", 7, id="l1")
    if first is None:
        cited = path.read_text(encoding="utf-8").splitlines()[6:9]
        prompt.update(quote="\n".join(cited), end_line=9)
    else:
        prompt.update(first)
    record = make_record(
        id="inv-1",
        mechanism="M6",
        pattern="concealment_instruction",
        surface=surface_of(plan, "prompt", "persona.py", 7),
        links=[
            prompt,
            link(root, "intervention", "persona.py", 19, id="l2", how="traced", **{"from": "l1"}),
        ],
        decision="violates_policy",
    )
    records = tmp_path / "records"
    write_record(records, record, skeptic="upheld")
    for name, content in (files or {}).items():
        (records / name).write_text(json.dumps(content), encoding="utf-8")
    doc = run_assessment(root, [records]).document
    assert doc is not None and [r["id"] for r in doc["machine"]["records"]] == ["inv-1"]
    return doc


def _assert_report_is_whole(text: str) -> None:
    """Every section of the report is there, once, and nothing was added to its outline."""
    lines = text.splitlines()
    assert [ln[3:] for ln in lines if ln.startswith("## ")] == list(_SECTIONS)
    assert [ln for ln in lines if ln.startswith("# ")] == ["# aisafe assessment"]
    mechanisms = [ln for ln in lines if ln.startswith("### ")]
    assert len(mechanisms) == len({ln.split()[1] for ln in mechanisms})
    assert not any(ln.startswith(("~~~", "```")) for ln in lines)
    assert "\r" not in text
    assert lines[-1].startswith("generated by")


@pytest.mark.parametrize(
    "second_line",
    ["<!-- tone notes for the writers", "~~~ tone notes for the writers", FORGED],
)
def test_a_cited_range_adds_no_line_to_the_report(tmp_path: Path, second_line: str) -> None:
    doc = _doc(tmp_path, second_line)
    assert second_line in doc["machine"]["records"][0]["links"][0]["quote"]
    text = render_markdown(doc)
    _assert_report_is_whole(text)
    assert "<!-- tone" not in text


def test_a_carriage_return_in_a_one_line_quote_adds_no_line(tmp_path: Path) -> None:
    doc = _doc(
        tmp_path, f"Tone notes {FORGED}", first={"line": 8, "quote": f"Tone notes\r{FORGED}"}
    )
    assert "\r" in doc["machine"]["records"][0]["links"][0]["quote"]
    _assert_report_is_whole(render_markdown(doc))


def test_a_line_break_in_a_rejected_id_adds_no_line(tmp_path: Path) -> None:
    bad = make_record(
        id="inv-2\n~~~ x",
        mechanism="M6",
        pattern="concealment_instruction",
        surface={"type": "prompt", "file": "persona.py", "line": 7},
        links=[],
        decision="needs_review",
    )
    doc = _doc(tmp_path, files={"bad.json": bad})
    assert doc["machine"]["rejected"]
    _assert_report_is_whole(render_markdown(doc))


@pytest.mark.parametrize(
    "value",
    ["# M6 forged", "###### M6 forged", "~~~ x", "> x", "- x", "+ x", "* x", "1. x", "2) x"]
    + ["[a]: https://example.invalid", "\t# M6 forged"],
)
def test_text_that_comes_first_in_an_item_opens_no_block(tmp_path: Path, value: str) -> None:
    """The id of a response is whatever its file says, and it starts the report's line."""
    doc = _doc(tmp_path)
    engagement = tmp_path / "eng"
    path = model.add_response(engagement, to="M6", by="P. Owner", text="Noted.")
    data = json.loads(path.read_text(encoding="utf-8"))
    path.write_text(json.dumps({**data, "id": value}), encoding="utf-8")
    doc["auditee"]["responses"] = model.load_responses(engagement)[0]
    doc["auditee"]["evidence"] = [
        {
            "id": "e1",
            "status": "open",
            "what": "w",
            "detail": "d",
            "documents": [{"path": value, "sha256": "ab", "state": "s"}],
        }
    ]
    text = render_markdown(doc)
    assert not [ln for ln in text.splitlines() if OPENS_A_BLOCK.match(ln)]
    _assert_report_is_whole(text)


@pytest.mark.parametrize("quote", ["a \\` b \\` c", "\\\\` b", "\\<!-- hide", "ends with \\"])
def test_a_backslash_cancels_no_escape(tmp_path: Path, quote: str) -> None:
    doc = _doc(tmp_path)
    doc["machine"]["records"][0]["links"][0]["quote"] = quote
    text = render_markdown(doc)
    line = next(ln for ln in text.splitlines() if ln.startswith("  - prompt ("))
    # An even run of backslashes before a backtick leaves it unescaped; an odd one at the
    # end of the line escapes nothing the quote wrote.
    for run in re.findall(r"(\\*)`", line):
        assert len(run) % 2 == 1, line
    assert len(re.search(r"\\*$", line).group()) % 2 == 0, line
    if "<" in quote:
        assert "\\\\&lt;" in line


@pytest.mark.parametrize(
    "quote", ["![](https://example.invalid/p.png)", "[approved](https://example.invalid)"]
)
def test_a_quote_makes_no_link_and_no_image(tmp_path: Path, quote: str) -> None:
    doc = _doc(tmp_path)
    doc["machine"]["records"][0]["links"][0]["quote"] = quote
    text = render_markdown(doc)
    assert "](" not in text and "https://example.invalid" in text


@pytest.mark.parametrize(
    "line",
    ["# aisafe assessment", "## Outcome", "### M6 x", "> disclaimer", "- plain", "  - plain"]
    + ["- 12 surfaces", "- not [first] here", "| a | b |"],
)
def test_the_renderers_own_lines_are_left_as_they_are(line: str) -> None:
    assert _md(line) == line


def test_a_parser_sees_the_report_and_every_quoted_word(tmp_path: Path) -> None:
    markdown_it = pytest.importorskip("markdown_it")
    doc = _doc(tmp_path)
    hostile = [
        "<!-- comment word",
        "<div hidden>div word</div>",
        "~~~ fence word",
        f"{FORGED} heading word",
        "![image word](https://example.invalid/p.png)",
        "[link word](https://example.invalid)",
        "\\` code word \\`",
    ]
    links = doc["machine"]["records"][0]["links"]
    template = links[0]
    links[:] = [{**template, "quote": f"x\n{quote}"} for quote in hostile]
    doc["auditee"]["responses"] = [
        {"id": quote, "to": "M6", "by": "b", "date": "d", "text": "t"} for quote in hostile
    ]
    tokens = markdown_it.MarkdownIt("commonmark").parse(render_markdown(doc))

    headings = [
        (token.tag, tokens[i + 1].content)
        for i, token in enumerate(tokens)
        if token.type == "heading_open"
    ]
    assert [t for t, _ in headings if t == "h2"] == ["h2"] * len(_SECTIONS)
    assert [t.level for t in tokens if t.type == "heading_open"] == [0] * len(headings)
    assert all(tag != "h1" or content == "aisafe assessment" for tag, content in headings)

    assert not [t for t in tokens if t.type in ("fence", "code_block")]
    assert len([t for t in tokens if t.type == "blockquote_open"]) == 1  # the disclaimer
    children = [c for t in tokens if t.type == "inline" for c in t.children or []]
    kinds = {c.type for c in children}
    assert not kinds & {"html_inline", "image", "link_open", "code_inline"}
    html_blocks = [t for t in tokens if t.type == "html_block"]
    assert len(html_blocks) == 1 and "aisafe-audit" in html_blocks[0].content

    shown = " ".join(c.content for c in children if c.type == "text")
    # Each one is shown as a quote, as a response and beside mechanism M6.
    for word in ("comment", "div", "fence", "heading", "image", "link", "code"):
        assert shown.count(f"{word} word") == 3, word
    assert shown.count("https://example.invalid") == 6
